import type { PGlite } from "@electric-sql/pglite";
import { beforeEach, describe, expect, it } from "vitest";
import { checkBlock } from "@/lib/catalog";
import { freshDb } from "@/lib/db";
import { fileState, take } from "@/lib/files";
import { uniqueName } from "@/lib/names";
import { pageNameOf } from "@/lib/pages";
import { seedIfEmpty } from "@/lib/seed";
import { copyPage, createPage, getComponent, getPage, listPages, saveComponent } from "@/lib/store";
import { exportDoc, importPageFile } from "@/lib/transfer";
import { checkIn, toPreview, versions } from "@/lib/workflow";

let pg: PGlite;
const built = async () => {};

beforeEach(async () => {
  pg = await freshDb();
  await seedIfEmpty(pg);
});

// The owner, 2026-11-16: 「it should be the page name itself, url should be its description … each page has its page
// name autogenerated without space and other chars, replace with _ , when you upload the same name with the file, it will
// be automatically checked out」.
describe("a page's name", () => {
  it("is made from its title, every run of what isn't a letter or a digit one _", () => {
    expect(pageNameOf({ en: "Help & support", zh: "客服与帮助" }, "/support/")).toBe("Help_support");
    // No English title: its address (S10: names in English alone).
    expect(pageNameOf({ zh: "新的活动页" }, "/events/")).toBe("events");
    expect(pageNameOf({ en: "禄命秘解 (Lu Ming Mi Jie)" }, "/works/lumingmijie/")).toBe("Lu_Ming_Mi_Jie");
    expect(pageNameOf({ en: "Cameyware | Software and App Development" }, "/")).toBe(
      "Cameyware_Software_and_App_Development",
    );
    expect(pageNameOf({ en: " — " }, "/works/lumingmijie/")).toBe("works_lumingmijie");
    expect(pageNameOf({}, "/")).toBe("home");
    expect(uniqueName("Contact", new Set(["Contact", "Contact_2"]))).toBe("Contact_3");
  });

  it("is given to every page, once, unique", async () => {
    const pages = await listPages(pg);
    expect(pages.find((p) => p.path === "/contact/")!.name).toBe("Contact");
    expect(new Set(pages.map((p) => p.name)).size).toBe(pages.length);
    const id = await createPage(pg, { path: "/contact-2/", title: { zh: "联系", en: "Contact" } }, "lee");
    expect((await getPage(pg, id))!.name).toBe("Contact_2");
  });
});

describe("a page copied", () => {
  it("has its settings and copies of its blocks, as new files of yours, apart from the page it came from", async () => {
    const from = (await listPages(pg)).find((p) => p.path === "/contact/")!;
    const id = await copyPage(
      pg,
      from.id,
      { path: "/contact-copy/", title: { zh: "联系我们（副本）" } },
      "lee",
    );
    const copy = (await getPage(pg, id))!;
    expect(copy).toMatchObject({ status: "inactive", layout: from.layout, name: "contact_copy" });
    expect(copy.blocks).toHaveLength(from.blocks.length);
    for (const [i, b] of copy.blocks.entries()) {
      const was = from.blocks[i]!;
      expect(b.id).not.toBe(was.id);
      expect({ zone: b.zone, style: b.style }).toEqual({ zone: was.zone, style: was.style });
      // The same content, as the catalog reads it (a new block has its defaults written out).
      const [mine, theirs] = [(await getComponent(pg, b.id))!, (await getComponent(pg, was.id))!];
      expect(checkBlock(mine.type, mine.data).value).toEqual(checkBlock(theirs.type, theirs.data).value);
      expect(await fileState(pg, "component", b.id)).toMatchObject({ status: "checked_out", owner: "lee" });
    }
    expect(await fileState(pg, "page", id)).toMatchObject({ status: "checked_out", owner: "lee" });
  });
});

describe("a page's file uploaded by its name", () => {
  it("goes onto the page of its name, taken for you; another name, or not the page picked, is refused", async () => {
    const page = (await listPages(pg)).find((p) => p.path === "/contact/")!;
    const doc = await exportDoc(pg, "page", page.id);
    expect(doc.kind === "webpage" && doc.page.name).toBe("Contact");
    const changed = JSON.stringify({
      ...doc,
      page: { ...(doc as { page: object }).page, title: { zh: "联系我们吧" } },
    });
    await expect(importPageFile(pg, "Nobody.json", changed, "lee", false)).rejects.toThrow(/Nobody/);
    const other = (await listPages(pg)).find((p) => p.path === "/works/")!;
    await expect(importPageFile(pg, "Contact.json", changed, "lee", false, other.id)).rejects.toThrow(
      /Contact/,
    );
    const plan = await importPageFile(pg, "Contact.json", changed, "lee", false, page.id);
    expect(plan.plan.items.find((i) => i.kind === "page")).toMatchObject({
      id: page.id,
      action: "update",
      take: true,
    });
    await importPageFile(pg, "Contact.json", changed, "lee", true);
    expect((await getPage(pg, page.id))!.title.zh).toBe("联系我们吧");
    expect(await fileState(pg, "page", page.id)).toMatchObject({ status: "checked_out", owner: "lee" });
  });
});

// The owner: 「for all files, if you push into preview, you can revert to that file version … everytime you pushed to
// preview, your version change is kept」.
it("marks each version with the preview releases it was in", async () => {
  const block = (await listPages(pg)).find((p) => p.path === "/contact/")!.blocks[0]!.id;
  const item = [{ kind: "component" as const, id: block }];
  await take(pg, item, "lee");
  await saveComponent(pg, block, { name: "pushed_once" }, "lee");
  await checkIn(pg, item, "预览一次", "lee");
  const r = await toPreview(pg, item, "lee", "", built);
  await r.done;
  const [latest] = await versions(pg, "component", block);
  expect(latest).toMatchObject({ message: "预览一次", previewed: [r.release] });
});

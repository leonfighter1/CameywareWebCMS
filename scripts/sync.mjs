// One home for each fact: what the CMS shares with the website and with 禄命秘解 comes from their repositories.
//   node scripts/sync.mjs     (SITE_REPO: ../Cameyware by default; LUMING_REPO: ../lumingApp)
// Writes src/generated (committed, so the CMS builds with this repository alone; never edited by hand):
//   model.ts        the website's content model (src/cms/model.ts): languages, pages, blocks, the snapshot
//   types.json      the website's catalog of block types (cms/types.json): every editor's fields, every upload's check
//   template.ts     the website's template markup (src/cms/template.ts): what a template may hold, its check
//   addresses.json  禄命秘解's config/addresses.json: the CMS's ports and addresses, the API's, the website's
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const site = resolve(root, process.env.SITE_REPO ?? "../Cameyware");
const luming = resolve(root, process.env.LUMING_REPO ?? "../lumingApp");
const write = (rel, text) => {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log("wrote", rel);
};

write(
  "src/generated/model.ts",
  "// GENERATED by npm run sync from the website's src/cms/model.ts. Change it there.\n" +
    readFileSync(join(site, "src", "cms", "model.ts"), "utf8"),
);
write("src/generated/types.json", readFileSync(join(site, "cms", "types.json"), "utf8"));
write(
  "src/generated/template.ts",
  "// GENERATED by npm run sync from the website's src/cms/template.ts. Change it there.\n" +
    readFileSync(join(site, "src", "cms", "template.ts"), "utf8"),
);
const addresses = JSON.parse(readFileSync(join(luming, "config", "addresses.json"), "utf8"));
delete addresses._readme;
write(
  "src/generated/addresses.json",
  JSON.stringify(
    {
      _readme: "GENERATED by npm run sync from 禄命秘解's config/addresses.json. Change it there.",
      ...addresses,
    },
    null,
    2,
  ) + "\n",
);
